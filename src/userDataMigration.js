'use strict'

//One-time copy of the Electron profile from the 5.x userData dir to the 6.x one.
//Up to 5.3.1 package.json "name" was "EpicWallet"; 6.0.0 renamed it to "epic-desktop-wallet".
//Electron names userData after it, so the address book (IndexedDB), Local Storage etc. stayed
//behind in <appData>/EpicWallet and 6.x started empty. Wallet files in ~/.epic are not affected.
//Runs in the main process before anything opens the session. Copies, never moves or deletes the
//old dir, never overwrites data in the new one, and never throws: the app must always start.

const fs = require('fs')
const path = require('path')

const OLD_DIR_NAME = 'EpicWallet'
const MARKER = '.migrated-from-EpicWallet'
//The profile folder name, frozen. Electron names userData after package.json, so renaming the
//package (as 6.0.0 did) would silently start every user with an empty profile again. Never change it.
const USERDATA_DIR_NAME = 'epic-desktop-wallet'

//Point userData at <appData>/epic-desktop-wallet whatever package.json says. Call before anything
//reads userData (the migration, sessions, windows, electron-log). Never throws.
function pinUserDataDir(app, log = console) {
  try {
    const dir = path.join(app.getPath('appData'), USERDATA_DIR_NAME)
    if (!samePath(app.getPath('userData'), dir)) {
      log.info(`userData: using ${dir} instead of ${app.getPath('userData')}`)
    }
    app.setPath('userData', dir)
    return dir
  } catch (e) {
    log.error('userData: could not pin the folder: ' + (e && e.message))
    return null
  }
}

//regenerated by Chromium, machine specific, or a lock of the running instance
const SKIP = new Set([
  'Cache', 'Code Cache', 'GPUCache', 'DawnCache', 'DawnGraphiteCache', 'DawnWebGPUCache',
  'GrShaderCache', 'ShaderCache', 'Crashpad', 'CacheStorage', 'ScriptCache', 'Service Worker',
  'blob_storage_tmp', 'DevToolsActivePort', 'SingletonLock', 'SingletonCookie', 'SingletonSocket',
  'lockfile', 'logs'
])

//user data the app writes from the renderer; if any is present the new dir is already in use
const DATA_DIRS = ['IndexedDB', 'Local Storage']

function isNonEmptyDir(dir) {
  try {
    return fs.statSync(dir).isDirectory() && fs.readdirSync(dir).length > 0
  } catch (e) {
    return false
  }
}

function hasUserData(dir) {
  return DATA_DIRS.some((d) => isNonEmptyDir(path.join(dir, d)))
}

function samePath(a, b) {
  const ra = path.resolve(a)
  const rb = path.resolve(b)
  //Windows and macOS file systems are case-insensitive by default
  return process.platform === 'linux' ? ra === rb : ra.toLowerCase() === rb.toLowerCase()
}

function copyFilter(src) {
  if (SKIP.has(path.basename(src))) return false
  try {
    return !fs.lstatSync(src).isSymbolicLink()
  } catch (e) {
    return false
  }
}

function writeMarker(newDir, result) {
  fs.mkdirSync(newDir, { recursive: true })
  fs.writeFileSync(path.join(newDir, MARKER), JSON.stringify({ result, date: new Date().toISOString() }) + '\n')
}

//returns what happened, for the log and the tests:
//'same-dir' | 'no-old-dir' | 'already-done' | 'new-dir-in-use' | 'migrated' | 'error'
function migrateUserData({ oldDir, newDir, log = console }) {
  const staging = newDir + '.migrating'
  try {
    if (samePath(oldDir, newDir)) return 'same-dir'
    if (!isNonEmptyDir(oldDir)) return 'no-old-dir'
    if (fs.existsSync(path.join(newDir, MARKER))) return 'already-done'
    if (hasUserData(newDir)) {
      log.info(`userData migration: ${newDir} already has data, leaving ${oldDir} alone`)
      writeMarker(newDir, 'new-dir-in-use')
      return 'new-dir-in-use'
    }

    //copy into a staging dir next to the new one first, so a failed copy leaves no half profile
    fs.rmSync(staging, { recursive: true, force: true })
    fs.cpSync(oldDir, staging, { recursive: true, filter: copyFilter })
    fs.mkdirSync(newDir, { recursive: true })
    for (const name of fs.readdirSync(staging)) {
      const dst = path.join(newDir, name)
      if (fs.existsSync(dst)) {
        //something a fresh start made (e.g. Preferences): keep it, add only what is missing
        fs.cpSync(path.join(staging, name), dst, { recursive: true, force: false, errorOnExist: false })
      } else {
        fs.renameSync(path.join(staging, name), dst)
      }
    }
    fs.rmSync(staging, { recursive: true, force: true })
    writeMarker(newDir, 'migrated')
    log.info(`userData migration: copied ${oldDir} to ${newDir}`)
    return 'migrated'
  } catch (e) {
    log.error('userData migration failed, starting without it: ' + (e && e.message))
    try {
      fs.rmSync(staging, { recursive: true, force: true })
    } catch (e2) {
      //ignore, the next start removes it
    }
    return 'error'
  }
}

//the 5.x dir sits next to the current userData dir, under the same appData root
function migrateFromEpicWallet(app, log) {
  try {
    const newDir = app.getPath('userData')
    const oldDir = path.join(app.getPath('appData'), OLD_DIR_NAME)
    return migrateUserData({ oldDir, newDir, log })
  } catch (e) {
    log.error('userData migration skipped: ' + (e && e.message))
    return 'error'
  }
}

module.exports = { migrateUserData, migrateFromEpicWallet, pinUserDataDir, USERDATA_DIR_NAME, MARKER, SKIP }
